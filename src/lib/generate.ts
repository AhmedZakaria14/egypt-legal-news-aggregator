// توليد مسودات المحتوى (بوست فيسبوك / سكربت فيديو) عبر Claude.
// المسودات تُحفظ في قاعدة البيانات ولا تُنشر تلقائياً في أي مكان.
import type { Story } from "./db";
import { callClaude, generationModel, MISSING_KEY_ERROR, hasApiKey } from "./claude";

// تعليمات النظام الصارمة — تُستخدم حرفياً كما هي في الأصل
export const GENERATION_SYSTEM = `أنت كاتب محتوى لمؤسسة عمرو منصور للمحاماة والاستشارات القانونية. اكتب اعتماداً فقط على بيانات الخبر المعطاة لك (العنوان والملخص والزاوية القانونية والمصدر) — ممنوع منعاً باتاً اختراع مواد قانونية أو أرقام قوانين أو أحكام أو وقائع غير موجودة في الخبر. إذا لم تكفِ المعلومات لذكر مادة قانونية محددة، اشرح المبدأ القانوني العام دون نسبة رقم مادة. النبرة مهنية وموثوقة ومبسطة للجمهور العام، دون أي وعود بنتائج قضايا.`;

function storyBlock(story: Story): string {
  return [
    `العنوان: ${story.title}`,
    `الملخص: ${story.description || "(لا يوجد ملخص — اعتمد على العنوان فقط)"}`,
    `الزاوية القانونية: ${story.legalAngle || "(غير محددة — استنتج بحذر من العنوان والملخص فقط دون اختراع وقائع)"}`,
    `المصدر: ${story.sourceName} — ${story.link}`,
  ].join("\n");
}

const POST_INSTRUCTIONS = `اكتب بوست فيسبوك جاهزاً للنشر على صفحة المؤسسة حول هذا الخبر، بهذا الهيكل:
1) سطر افتتاحي جاذب للانتباه (Hook) يلخّص أهمية الخبر.
2) شرح مبسط للمعلومة القانونية المستفادة من الخبر اعتماداً على بياناته فقط.
3) نصيحة عملية واحدة للمتابعين مرتبطة بالموضوع.
4) سؤال تفاعلي أو دعوة للاستشارة القانونية في النهاية.
5) التوقيع في آخر سطر منفصل: مؤسسة عمرو منصور للمحاماة والاستشارات القانونية
اكتب البوست فقط، دون أي مقدمات أو شرح عن مهمتك.`;

const SCRIPT_INSTRUCTIONS = `اكتب سكربت فيديو قصير (من 60 إلى 90 ثانية عند الإلقاء) يقدّمه محامٍ من المؤسسة حول هذا الخبر، بهذا الهيكل:
1) خطّاف (Hook) في أول 3 ثوانٍ يجذب المشاهد.
2) شرح المعلومة القانونية المستفادة من الخبر اعتماداً على بياناته فقط، بلغة منطوقة بسيطة.
3) خاتمة عملية (نصيحة أو خطوة تالية للمشاهد) مع ذكر اسم المؤسسة: مؤسسة عمرو منصور للمحاماة والاستشارات القانونية.
اكتب نص السكربت المنطوق فقط، دون تعليمات تصوير أو مقدمات عن مهمتك.`;

export async function generateDraftText(
  story: Story,
  type: "post" | "script"
): Promise<string> {
  if (!hasApiKey()) throw new Error(MISSING_KEY_ERROR);
  const instructions = type === "post" ? POST_INSTRUCTIONS : SCRIPT_INSTRUCTIONS;
  const text = await callClaude({
    model: generationModel(),
    system: GENERATION_SYSTEM,
    user: `${instructions}\n\nبيانات الخبر:\n${storyBlock(story)}`,
    maxTokens: 2048,
  });
  return text;
}
